def set_seed(seed: int):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def save_json(path: Path, obj: Any):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)


def parse_roi_types(x: str) -> List[str]:
    return [v.strip() for v in x.split(",") if v.strip()]


def parse_float_list(x: str) -> List[float]:
    return [float(v.strip()) for v in x.split(",") if v.strip()]


def read_manifest(path: Path, prepared_root: Path, roi_type: str) -> List[Dict[str, Any]]:
    rows = []
    if not path.exists():
        raise FileNotFoundError(f"Manifest not found: {path}")
    with open(path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for r in reader:
            img = prepared_root / r["image"]
            mask = prepared_root / r["mask"]
            if img.exists() and mask.exists():
                rr = dict(r)
                rr["image_path"] = str(img)
                rr["mask_path"] = str(mask)
                rr["roi_type"] = roi_type
                rows.append(rr)
    return rows


def letterbox_pair(
    img: Image.Image,
    mask: Image.Image,
    target_w: int,
    target_h: int,
    image_fill=(0, 0, 0),
    mask_fill=0,
):
    """
    Keep aspect ratio and pad to target size.

    Input:
      img/mask: original ROI image and binary mask
    Output:
      padded image/mask with size (target_w, target_h)

    This avoids geometric distortion caused by direct resize.
    """
    src_w, src_h = img.size
    if src_w <= 0 or src_h <= 0:
        raise ValueError(f"Invalid image size: {img.size}")

    scale = min(target_w / src_w, target_h / src_h)
    new_w = max(1, int(round(src_w * scale)))
    new_h = max(1, int(round(src_h * scale)))

    img_resized = img.resize((new_w, new_h), Image.BILINEAR)
    mask_resized = mask.resize((new_w, new_h), Image.NEAREST)

    canvas_img = Image.new("RGB", (target_w, target_h), image_fill)
    canvas_mask = Image.new("L", (target_w, target_h), mask_fill)

    pad_x = (target_w - new_w) // 2
    pad_y = (target_h - new_h) // 2

    canvas_img.paste(img_resized, (pad_x, pad_y))
    canvas_mask.paste(mask_resized, (pad_x, pad_y))

    return canvas_img, canvas_mask


class ROISegDataset(Dataset):
    def __init__(
        self,
        rows: List[Dict[str, Any]],
        image_size: Tuple[int, int] = (512, 512),
        train: bool = True,
        augment: bool = True,
        resize_mode: str = "letterbox",
    ):
        self.rows = rows
        self.image_size = tuple(image_size)
        self.train = train
        self.augment = augment and train
        self.resize_mode = resize_mode

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, idx):
        r = self.rows[idx]
        img = Image.open(r["image_path"]).convert("RGB")
        mask = Image.open(r["mask_path"]).convert("L")

        # Resize / Letterbox
        target_h, target_w = self.image_size[0], self.image_size[1]
        if self.resize_mode == "letterbox":
            img, mask = letterbox_pair(img, mask, target_w=target_w, target_h=target_h)
        else:
            img = img.resize((target_w, target_h), Image.BILINEAR)
            mask = mask.resize((target_w, target_h), Image.NEAREST)

        img_np = np.asarray(img).astype(np.float32) / 255.0
        mask_np = (np.asarray(mask).astype(np.float32) > 127).astype(np.float32)

        if self.augment:
            if random.random() < 0.5:
                img_np = np.ascontiguousarray(img_np[:, ::-1, :])
                mask_np = np.ascontiguousarray(mask_np[:, ::-1])
            if random.random() < 0.5:
                img_np = np.ascontiguousarray(img_np[::-1, :, :])
                mask_np = np.ascontiguousarray(mask_np[::-1, :])

        # ImageNet normalization
        mean = np.array([0.485, 0.456, 0.406], dtype=np.float32)
        std = np.array([0.229, 0.224, 0.225], dtype=np.float32)
        img_np = (img_np - mean) / std

        img_t = torch.from_numpy(img_np.transpose(2, 0, 1)).float()
        mask_t = torch.from_numpy(mask_np[None, ...]).float()
        return img_t, mask_t, r["roi_type"]


class DiceBCELoss(nn.Module):
    def __init__(self, dice_weight=1.0, bce_weight=1.0, pos_weight=1.0, eps=1e-6):
        super().__init__()
        self.dice_weight = dice_weight
        self.bce_weight = bce_weight
        self.eps = eps
        self.register_buffer("pos_weight", torch.tensor([float(pos_weight)], dtype=torch.float32))
        self.bce = nn.BCEWithLogitsLoss(pos_weight=self.pos_weight)

    def forward(self, logits, target):
        bce = self.bce(logits, target)
        prob = torch.sigmoid(logits)
        dims = (1, 2, 3)
        inter = (prob * target).sum(dims)
        union = prob.sum(dims) + target.sum(dims)
        dice = (2 * inter + self.eps) / (union + self.eps)
        dice_loss = 1.0 - dice.mean()
        return self.bce_weight * bce + self.dice_weight * dice_loss


def build_model(encoder_name: str, pretrained: bool):
    weights = "imagenet" if pretrained else None
    return smp.DeepLabV3Plus(
        encoder_name=encoder_name,
        encoder_weights=weights,
        in_channels=3,
        classes=1,
        activation=None,
    )


def compute_metrics_from_logits(logits, target, threshold=0.5, eps=1e-7):
    prob = torch.sigmoid(logits)
    pred = (prob >= threshold).float()
    target = (target > 0.5).float()

    B = pred.shape[0]
    pred_f = pred.view(B, -1)
    tgt_f = target.view(B, -1)

    tp = (pred_f * tgt_f).sum(dim=1)
    fp = (pred_f * (1 - tgt_f)).sum(dim=1)
    fn = ((1 - pred_f) * tgt_f).sum(dim=1)
    tn = ((1 - pred_f) * (1 - tgt_f)).sum(dim=1)

    dice = (2 * tp + eps) / (2 * tp + fp + fn + eps)
    iou = (tp + eps) / (tp + fp + fn + eps)
    precision = (tp + eps) / (tp + fp + eps)
    recall = (tp + eps) / (tp + fn + eps)
    pixel_acc = (tp + tn + eps) / (tp + fp + fn + tn + eps)

    return {
        "sum_tp": float(tp.sum().item()),
        "sum_fp": float(fp.sum().item()),
        "sum_fn": float(fn.sum().item()),
        "sum_tn": float(tn.sum().item()),
        "mean_dice": float(dice.mean().item()),
        "mean_iou": float(iou.mean().item()),
        "precision": float(precision.mean().item()),
        "recall": float(recall.mean().item()),
        "mpixelacc": float(pixel_acc.mean().item()),
    }


def aggregate_metrics(parts: List[Dict[str, float]], eps=1e-7):
    if not parts:
        return {}
    n = len(parts)
    mean_keys = ["mean_dice", "mean_iou", "precision", "recall", "mpixelacc"]
    out = {k: float(np.mean([p[k] for p in parts])) for k in mean_keys}

    tp = sum(p["sum_tp"] for p in parts)
    fp = sum(p["sum_fp"] for p in parts)
    fn = sum(p["sum_fn"] for p in parts)
    tn = sum(p["sum_tn"] for p in parts)

    out["global_dice"] = float((2 * tp + eps) / (2 * tp + fp + fn + eps))
    out["global_iou"] = float((tp + eps) / (tp + fp + fn + eps))
    out["global_pixel_acc"] = float((tp + tn + eps) / (tp + fp + fn + tn + eps))
    return out


def train_one_epoch(model, loader, optimizer, loss_fn, device, amp, scaler):
    model.train()
    losses = []
    pbar = tqdm(loader, desc="[TRAIN]", leave=False)
    optimizer.zero_grad(set_to_none=True)

    for img, mask, _ in pbar:
        img = img.to(device, non_blocking=True)
        mask = mask.to(device, non_blocking=True)

        with torch.cuda.amp.autocast(enabled=amp):
            logits = model(img)
            loss = loss_fn(logits, mask)

        if scaler is not None and amp:
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
        else:
            loss.backward()
            optimizer.step()

        optimizer.zero_grad(set_to_none=True)
        losses.append(float(loss.item()))
        pbar.set_postfix(loss=f"{np.mean(losses):.4f}")
    return float(np.mean(losses)) if losses else 0.0


@torch.no_grad()
def validate(model, loader, loss_fn, device, amp, thresholds: List[float]):
    model.eval()
    losses = []
    parts_by_threshold = {float(t): [] for t in thresholds}
    pbar = tqdm(loader, desc="[VAL]", leave=False)

    for img, mask, _ in pbar:
        img = img.to(device, non_blocking=True)
        mask = mask.to(device, non_blocking=True)

        with torch.cuda.amp.autocast(enabled=amp):
            logits = model(img)
            loss = loss_fn(logits, mask)

        losses.append(float(loss.item()))
        for t in parts_by_threshold:
            parts_by_threshold[t].append(compute_metrics_from_logits(logits, mask, threshold=t))

    out = {}
    for t, parts in parts_by_threshold.items():
        out[f"{t:.3f}"] = aggregate_metrics(parts)
        out[f"{t:.3f}"]["val_loss"] = float(np.mean(losses)) if losses else 0.0
    return out


def select_threshold_metrics(threshold_metrics: Dict[str, Dict[str, float]], metric_name: str) -> Tuple[float, Dict[str, float]]:
    best_t = None
    best_metrics = None
    best_value = -float("inf")
    for t_str, metrics in threshold_metrics.items():
        value = float(metrics.get(metric_name, -float("inf")))
        if value > best_value:
            best_value = value
            best_t = float(t_str)
            best_metrics = metrics
    if best_t is None or best_metrics is None:
        raise RuntimeError("No threshold metrics were produced.")
    return best_t, best_metrics


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--prepared-root", required=True)
    p.add_argument("--roi-types", default="leaf_roi", help="Default ROI types for both train and val.")
    p.add_argument("--train-roi-types", default=None, help="Optional ROI types used only for training.")
    p.add_argument("--val-roi-types", default=None, help="Optional ROI types used only for validation.")
    p.add_argument("--save-dir", required=True)

    p.add_argument("--encoder-name", default="resnet34")
    p.add_argument("--pretrained-encoder", action="store_true")
    p.add_argument("--image-size", nargs=2, type=int, default=[512, 512],
                   help="Input size as H W. With letterbox, final tensor is still HxW, but aspect ratio is preserved.")
    p.add_argument("--resize-mode", choices=["letterbox", "direct"], default="letterbox",
                   help="letterbox keeps aspect ratio + padding; direct stretches ROI to image-size.")
    p.add_argument("--epochs", type=int, default=80)
    p.add_argument("--batch-size", type=int, default=8)
    p.add_argument("--num-workers", type=int, default=4)
    p.add_argument("--lr", type=float, default=3e-4)
    p.add_argument("--weight-decay", type=float, default=1e-4)
    p.add_argument("--dice-weight", type=float, default=1.0)
    p.add_argument("--bce-weight", type=float, default=1.0)
    p.add_argument("--pos-weight", type=float, default=1.0,
                   help="BCE positive class weight. Increase slightly if recall is too low.")
    p.add_argument("--prob-threshold", type=float, default=0.5)
    p.add_argument("--thresholds", type=str, default="0.30,0.35,0.40,0.45,0.50,0.55,0.60,0.65,0.70",
                   help="Validation probability thresholds to sweep.")
    p.add_argument("--best-metric", choices=["mean_dice", "global_dice", "mean_iou", "global_iou"],
                   default="global_dice",
                   help="Metric used for best.pth. global_dice is usually closer to final whole-image evaluation.")
    p.add_argument("--patience", type=int, default=15)
    p.add_argument("--min-delta", type=float, default=1e-4)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--amp", action="store_true")
    return p.parse_args()


def main():
    args = parse_args()
    set_seed(args.seed)

    prepared_root = Path(args.prepared_root)
    save_dir = Path(args.save_dir)
    save_dir.mkdir(parents=True, exist_ok=True)

    roi_types = parse_roi_types(args.roi_types)
    train_roi_types = parse_roi_types(args.train_roi_types) if args.train_roi_types else roi_types
    val_roi_types = parse_roi_types(args.val_roi_types) if args.val_roi_types else roi_types
    train_rows, val_rows = [], []
    for rt in train_roi_types:
        train_rows += read_manifest(prepared_root / "deeplab_roi" / rt / "manifest_train.csv", prepared_root, rt)
    for rt in val_roi_types:
        val_rows += read_manifest(prepared_root / "deeplab_roi" / rt / "manifest_val.csv", prepared_root, rt)

    if not train_rows or not val_rows:
        raise RuntimeError(f"No train/val rows found. train={len(train_rows)} val={len(val_rows)}")

    train_ds = ROISegDataset(
        train_rows,
        image_size=tuple(args.image_size),
        train=True,
        augment=True,
        resize_mode=args.resize_mode,
    )
    val_ds = ROISegDataset(
        val_rows,
        image_size=tuple(args.image_size),
        train=False,
        augment=False,
        resize_mode=args.resize_mode,
    )

    train_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                              num_workers=args.num_workers, pin_memory=True, drop_last=False)
    val_loader = DataLoader(val_ds, batch_size=args.batch_size, shuffle=False,
                            num_workers=args.num_workers, pin_memory=True, drop_last=False)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    amp = bool(args.amp and device.type == "cuda")

    model = build_model(args.encoder_name, args.pretrained_encoder).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    loss_fn = DiceBCELoss(dice_weight=args.dice_weight, bce_weight=args.bce_weight, pos_weight=args.pos_weight).to(device)
    scaler = torch.cuda.amp.GradScaler(enabled=amp)
    thresholds = parse_float_list(args.thresholds) or [float(args.prob_threshold)]

    cfg = vars(args).copy()
    cfg["num_train"] = len(train_ds)
    cfg["num_val"] = len(val_ds)
    cfg["roi_types"] = roi_types
    cfg["train_roi_types"] = train_roi_types
    cfg["val_roi_types"] = val_roi_types
    cfg["thresholds"] = thresholds
    save_json(save_dir / "config.json", cfg)

    print("=" * 90)
    print("DeepLabV3+ binary ROI training")
    print(f"prepared_root : {prepared_root}")
    print(f"roi_types     : {roi_types}")
    print(f"train_roi_types: {train_roi_types}")
    print(f"val_roi_types : {val_roi_types}")
    print(f"resize_mode   : {args.resize_mode}")
    print(f"image_size    : {args.image_size}")
    print(f"train samples : {len(train_ds)}")
    print(f"val samples   : {len(val_ds)}")
    print(f"device        : {device}")
    print(f"amp           : {amp}")
    print("=" * 90)

    history = []
    best_dice = -1.0
    best_epoch = 0
    best_threshold = float(args.prob_threshold)
    bad_epochs = 0

    for epoch in range(1, args.epochs + 1):
        t0 = time.time()
        train_loss = train_one_epoch(model, train_loader, optimizer, loss_fn, device, amp, scaler)
        threshold_metrics = validate(model, val_loader, loss_fn, device, amp, thresholds=thresholds)
        best_t_this_epoch, val = select_threshold_metrics(threshold_metrics, args.best_metric)
        used = time.time() - t0

        rec = {
            "epoch": epoch,
            "train_loss": train_loss,
            "best_threshold": best_t_this_epoch,
            "threshold_metrics": threshold_metrics,
            **val,
            "time_sec": used,
        }
        history.append(rec)
        save_json(save_dir / "history.json", history)

        print(
            f"[{epoch:03d}/{args.epochs:03d}] "
            f"train_loss={train_loss:.4f} val_loss={val['val_loss']:.4f} "
            f"val_iou={val['mean_iou']:.4f} val_dice={val['mean_dice']:.4f} "
            f"val_prec={val['precision']:.4f} val_rec={val['recall']:.4f} "
            f"global_dice={val['global_dice']:.4f} "
            f"thr={best_t_this_epoch:.2f} time={used/60:.1f}min"
        )

        ckpt = {
            "model": model.state_dict(),
            "optimizer": optimizer.state_dict(),
            "epoch": epoch,
            "best_dice": best_dice,
            "best_metric": args.best_metric,
            "best_threshold": best_threshold,
            "config": cfg,
        }
        torch.save(ckpt, save_dir / "last.pth")

        current_score = float(val[args.best_metric])
        improved = current_score - best_dice > args.min_delta
        if improved:
            best_dice = current_score
            best_epoch = epoch
            best_threshold = best_t_this_epoch
            bad_epochs = 0
            ckpt["best_dice"] = best_dice
            ckpt["best_threshold"] = best_threshold
            torch.save(ckpt, save_dir / "best.pth")
            print(f"[INFO] best updated: epoch={epoch}, {args.best_metric}={best_dice:.6f}, threshold={best_threshold:.3f}")
        else:
            bad_epochs += 1

        if bad_epochs >= args.patience:
            print(f"[INFO] early stopping at epoch {epoch}. best_epoch={best_epoch}, best_{args.best_metric}={best_dice:.6f}, best_threshold={best_threshold:.3f}")
            break

    print("=" * 90)
    print(f"Finished. best_epoch={best_epoch}, best_{args.best_metric}={best_dice:.6f}, best_threshold={best_threshold:.3f}")
    print(f"save_dir: {save_dir}")
    print("=" * 90)


if __name__ == "__main__":
    main()




