"""
train_deeplabv3plus_binary_from_roi_manifest_letterbox.py

Train a binary DeepLabV3+ segmentation model from ROI manifests generated by:
  prepare_leafdisease_with_leaf_roi_v2.py

Supported training modes
------------------------
1) leaf-level global branch:
   --roi-types leaf_roi

   Input : leaf ROI image
   Target: disease mask inside leaf ROI

2) lesion local branch:
   --roi-types lesion_roi

   Input : lesion ROI image
   Target: disease mask inside lesion ROI

3) combined ablation:
   --roi-types leaf_roi,lesion_roi

   This mixes leaf-level global ROI and lesion-level local ROI in one model.
   It is NOT recommended as the main method, but can be used as an ablation.

Recommended commands
--------------------

A. Train leaf-level global DeepLabV3+
python train_deeplabv3plus_binary_from_roi_manifest_letterbox.py \
  --prepared-root prepared_leaf_disease_leaf_level \
  --roi-types leaf_roi \
  --save-dir runs/deeplab_leaf_level_global \
  --encoder-name resnet34 \
  --pretrained-encoder \
  --image-size 512 512 \
  --epochs 80 \
  --batch-size 8 \
  --num-workers 4 \
  --lr 3e-4 \
  --weight-decay 1e-4 \
  --resize-mode letterbox \
  --amp

B. Train lesion local DeepLabV3+
python train_deeplabv3plus_binary_from_roi_manifest_letterbox.py \
  --prepared-root prepared_leaf_disease_leaf_level \
  --roi-types lesion_roi \
  --save-dir runs/deeplab_lesion_local \
  --encoder-name resnet34 \
  --pretrained-encoder \
  --image-size 512 512 \
  --epochs 80 \
  --batch-size 8 \
  --num-workers 4 \
  --lr 3e-4 \
  --weight-decay 1e-4 \
  --resize-mode letterbox \
  --amp
"""

